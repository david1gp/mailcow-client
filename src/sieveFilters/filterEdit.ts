import * as a from "valibot"
import { createResultError, type PromiseResult } from "#result"
import { bodyOmitUndefined } from "../client/bodyOmitUndefined.js"
import { mailcowEnvelope } from "../client/mailcowEnvelope.js"
import { mailcowPathApi } from "../client/mailcowPathApi.js"
import { mailcowRequest } from "../client/mailcowRequest.js"
import type { FilterEditOptions } from "./filterEditOptionsSchema.js"
import { filterEditOptionsSchema } from "./filterEditOptionsSchema.js"

/**
 * `POST /edit/filter`. Raw JSON body is `{attr, items}`
 * (`json_api.php:1973-1975`).
 */
export async function filterEdit(options: FilterEditOptions): PromiseResult<string[]> {
  const op = "filterEdit"
  const parsed = a.safeParse(filterEditOptionsSchema, options)
  if (!parsed.success) return createResultError(op, a.summarize(parsed.issues))
  const { config, items, attr } = parsed.output
  const requested = await mailcowRequest({
    config,
    method: "POST",
    path: mailcowPathApi("/edit/filter"),
    body: { attr: bodyOmitUndefined(attr), items },
  })
  if (!requested.success) return requested
  const enveloped = mailcowEnvelope(requested.data)
  if (!enveloped.success) return createResultError(op, enveloped.errorMessage)
  return enveloped
}
